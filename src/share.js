const B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';

const bytesToB64 = bytes => {
  let bin = '';
  for (const b of bytes) bin += String.fromCharCode(b);
  return btoa(bin).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
};
const b64ToBytes = s => {
  const bin = atob(s.replace(/-/g, '+').replace(/_/g, '/') + '='.repeat((4 - s.length % 4) % 4));
  return Uint8Array.from(bin, c => c.charCodeAt(0));
};

const encodeDense = levels => {
  let n = 0n;
  for (const code of CODES_V1) n = n * 6n + BigInt(levels[code] ?? 0);
  const bytes = [];
  while (n > 0n) { bytes.unshift(Number(n & 255n)); n >>= 8n; }
  return bytesToB64(bytes);
};
const decodeDense = s => {
  let n = 0n;
  for (const b of b64ToBytes(s)) n = (n << 8n) | BigInt(b);
  const levels = {};
  for (let i = CODES_V1.length - 1; i >= 0; i--) {
    const lv = Number(n % 6n);
    n /= 6n;
    if (lv) levels[CODES_V1[i]] = lv;
  }
  if (n !== 0n) throw new Error('数据超出范围');
  return levels;
};

const encodeSparse = levels => CODES_V1.map((code, i) => {
  const lv = levels[code];
  if (!lv) return '';
  const v = (i << 3) | (lv - 1); // 12 位
  return B64[v >> 6] + B64[v & 63];
}).join('');
const decodeSparse = s => {
  if (s.length % 2) throw new Error('长度不对');
  const levels = {};
  for (let i = 0; i < s.length; i += 2) {
    const a = B64.indexOf(s[i]), b = B64.indexOf(s[i + 1]);
    if (a < 0 || b < 0) throw new Error('非法字符');
    const v = (a << 6) | b, idx = v >> 3, lv = (v & 7) + 1;
    if (idx >= CODES_V1.length || lv > 5) throw new Error('数据超出范围');
    levels[CODES_V1[idx]] = lv;
  }
  return levels;
};

export const cleanName = name => [...(name ?? '').replace(/[\u0000-\u001f<>]/g, '').trim()].slice(0, MAX_NAME).join('');

// levels：{ 代码: 等级 }；返回 hash（含 #/s/ 前缀）
export const encodeShare = (levels, name = '') => {
  const dense = '1d' + encodeDense(levels), sparse = '1s' + encodeSparse(levels);
  const nick = cleanName(name);
  return SHARE_PREFIX + (sparse.length <= dense.length ? sparse : dense)
    + (nick ? '.' + bytesToB64(new TextEncoder().encode(nick)) : '');
};

// 从 hash 解出 { levels, name, key }（key：不含省份后缀的分享部分，用于在查看模式里拼省份网址）；不是分享链接或已损坏返回 null
export const decodeShare = hash => {
  const m = hash.match(/^#\/s\/(1[ds])([A-Za-z0-9_-]*)(?:\.([A-Za-z0-9_-]+))?(?:\/\d{6})?$/);
  if (!m) return null;
  try {
    const levels = m[1] === '1d' ? decodeDense(m[2]) : decodeSparse(m[2]);
    const name = m[3] ? cleanName(new TextDecoder('utf-8', { fatal: true }).decode(b64ToBytes(m[3]))) : '';
    return { levels, name, key: `${SHARE_PREFIX}${m[1]}${m[2]}${m[3] ? '.' + m[3] : ''}` };
  } catch {
    return null;
  }
};

export const isShareHash = hash => hash.startsWith(SHARE_PREFIX);
